def desenharRetangulo(t, largura, altura):
    for _ in range(2):
        t.fd(largura)
        t.lt(90)
        t.fd(altura)
        t.lt(90)
def desenharEstrela(t, tamanho):
    for _ in range(5):
        t.forward(tamanho)
        t.right(144)

